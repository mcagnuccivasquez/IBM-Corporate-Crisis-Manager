"""A5 report rendering: CaseState -> HTML -> PDF.

Code only, no LLM. Every table in the report is filled straight from the CaseState
(PROJECT.md section 4), so numbers are copied exactly and nothing is invented.
The narrative paragraphs are read from state["report"]["narrative"] (written by the
A5 LLM step); if a field is empty the report prints "None reported".

Readability (agreed with Serdar, 2026-11-21): IDs stay in the report for traceability,
but citations become small clickable references, source IDs are shown with their
title, and a legend on page 1 explains the ID prefixes.
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from typing import Any

from jinja2 import ChainableUndefined, Environment, FileSystemLoader, pass_context
from markupsafe import Markup, escape

REPORT_DIR = Path(__file__).resolve().parent

RISK_LEVELS = ["Low", "Medium", "High", "Critical"]
PRIORITY_ORDER = {"P1": 0, "P2": 1, "P3": 2}
PRIORITY_LABELS = {"P1": "P1 · now", "P2": "P2 · this week", "P3": "P3 · later"}
STATUS_LABELS = {
    "proposed": "proposed",
    "approved": "approved",
    "in_progress": "in progress",
    "completed": "completed",
    "verified_effective": "verified ✓",
    "verified_ineffective": "verified ✗",
    "dropped": "dropped",
}
CATEGORY_LABELS = {
    "incident_evidence": "Incident evidence",
    "company_record": "Company record",
    "historical_case": "Historical case (precedent only)",
    "informal_note": "Informal note (not policy)",
    "planning_assumption": "Planning assumption",
    "reference": "Reference",
}
BASIS_LABELS = {
    "company_data": "Case data",
    "precedent": "ACME precedent",
    "general_knowledge": "General knowledge (not an ACME fact)",
}
TIMEFRAME_LABELS = {"24h": "within 24 hours", "7d": "within 7 days", "30d": "within 30 days"}
DOMAINS = [
    ("reputational", "Reputational"),
    ("economic", "Economic"),
    ("legal_regulatory", "Legal / regulatory"),
]
# Top-level CaseState fields (PROJECT.md section 4). Temporary check until src/contracts.py exists.
REQUIRED_FIELDS = ["case_id", "version", "status", "sources", "claims", "impacts", "risk",
                   "stakeholders", "actions", "outlook", "qa", "open_questions", "changelog"]
DISCLAIMER = (
    "Decision-support draft generated by the ACME Crisis Manager. "
    "Does not execute recalls, notifications or public statements."
)

ID_PATTERN = re.compile(r"\b(?:ACT|KB|C|U)-\d+\b")
_BRACKET = re.compile(r"\[([^\[\]]+)\]")


# ---------------------------------------------------------------- view helpers

def claim_change_label(claim: dict, version: int) -> str:
    """New / changed / unchanged, with the version (agreed with Serdar, 2026-11-21)."""
    if claim.get("first_seen_version") == version:
        return f"New in v{version}"
    if claim.get("last_changed_version") == version:
        return f"Changed in v{version}"
    return f"No change since v{claim.get('last_changed_version') or claim.get('first_seen_version')}"


def group_claims(claims: list[dict]) -> dict[str, list[dict]]:
    groups: dict[str, list[dict]] = {"confirmed": [], "unconfirmed": [], "disproved_or_misleading": []}
    for c in claims:
        status = c.get("status")
        if status in ("disproved", "misleading"):
            groups["disproved_or_misleading"].append(c)
        elif status in groups:
            groups[status].append(c)
        else:
            raise ValueError(f"Claim {c.get('claim_id')} has unknown status {status!r}")
    return groups


def sort_actions(actions: list[dict]) -> list[dict]:
    """Priority first (P1, P2, P3); inside a priority, focus-related actions first.

    `focus_related` is set by A3 (option C, proposed to the director). If the field
    is missing the action counts as not focus-related, so the order is priority-only.
    The sort is stable: otherwise the order from the state is kept.
    """
    return sorted(
        actions,
        key=lambda a: (PRIORITY_ORDER.get(a.get("priority"), len(PRIORITY_ORDER)),
                       0 if a.get("focus_related") is True else 1),
    )


def known_ids(state: dict) -> set[str]:
    ids = {c.get("claim_id") for c in state.get("claims") or []}
    ids |= {s.get("source_id") for s in state.get("sources") or []}
    ids |= {a.get("action_id") for a in state.get("actions") or []}
    ids.discard(None)
    return ids


def cited_source_ids(state: dict) -> list[str]:
    """Every source ID referenced anywhere in the state, in first-seen order."""
    ids: list[str] = []

    def add(values):
        for v in values or []:
            if v not in ids:
                ids.append(v)

    for c in state.get("claims") or []:
        add(c.get("source_ids"))
        add(c.get("contradicted_by"))
        for h in c.get("change_history") or []:
            add(h.get("source_ids"))
    for _, block in (state.get("impacts") or {}).items():
        for imp in (block or {}).get("impacts") or []:
            add(imp.get("source_ids"))
    for a in state.get("actions") or []:
        add(a.get("basis_source_ids"))
        add(a.get("result_evidence_source_ids"))
    for entry in state.get("changelog") or []:
        add(entry.get("new_source_ids"))
    return ids


def current_changelog(state: dict) -> dict | None:
    for entry in state.get("changelog") or []:
        if entry.get("version") == state.get("version"):
            return entry
    return None


def data_warnings(state: dict) -> list[str]:
    """Missing parts of the case data, printed in Appendix C instead of silently showing blanks."""
    warnings = [f"Field '{f}' is missing from the case data" for f in REQUIRED_FIELDS if f not in state]
    impacts = state.get("impacts") or {}
    if "impacts" in state:
        warnings += [f"Impact domain '{key}' is missing from the case data" for key, _ in DOMAINS if key not in impacts]
    if "risk" in state and not (state.get("risk") or {}).get("level"):
        warnings.append("Risk level is missing from the case data")
    return warnings


def format_timestamp(value: str | None) -> str:
    if not value:
        return "None reported"
    try:
        return datetime.fromisoformat(value).strftime("%d %b %Y, %H:%M %Z").strip().rstrip(",")
    except ValueError:
        return value


def risk_css(level: str | None) -> str:
    return level.lower() if level in RISK_LEVELS else "none"


# ---------------------------------------------------------------- ID links

def _id_html(id_: str, ids: set[str]) -> str:
    if id_ in ids:
        return f'<a class="ref" href="#ref-{id_}">{id_}</a>'
    return f'<span class="ref ref-unknown">{id_}</span>'


def _link_plain(text: str, ids: set[str]) -> str:
    out, pos = [], 0
    for m in ID_PATTERN.finditer(text):
        out.append(str(escape(text[pos:m.start()])))
        out.append(_id_html(m.group(0), ids))
        pos = m.end()
    out.append(str(escape(text[pos:])))
    return "".join(out)


def linkify(text: Any, ids: set[str]) -> Markup:
    """Escape text; turn [C-001, U-01] into a small superscript citation and other IDs into links."""
    if text is None or text == "":
        return Markup("")
    text = str(text)
    out, pos = [], 0
    for m in _BRACKET.finditer(text):
        parts = [p.strip() for p in m.group(1).split(",")]
        if parts and all(ID_PATTERN.fullmatch(p) for p in parts):
            out.append(_link_plain(text[pos:m.start()].rstrip(" "), ids))
            out.append('<sup class="cite">' + ", ".join(_id_html(p, ids) for p in parts) + "</sup>")
            pos = m.end()
    out.append(_link_plain(text[pos:], ids))
    return Markup("".join(out))


# ---------------------------------------------------------------- rendering

def _to_dict(state: Any) -> dict:
    # Accept the Pydantic CaseState from src/contracts.py as well as a plain dict.
    if hasattr(state, "model_dump"):
        return state.model_dump(mode="json")
    return state


def build_context(state: Any) -> dict:
    s = _to_dict(state)
    version = s["version"]
    sources_by_id = {src["source_id"]: src for src in s.get("sources") or []}
    cited = cited_source_ids(s)
    actions_sorted = sort_actions(s.get("actions") or [])
    report = s.get("report") or {}
    return {
        "s": s,
        "version": version,
        "is_initial": version == 1,
        "generated_at": format_timestamp(s.get("updated_at")),
        "narrative": report.get("narrative") or {},
        # None = checks never ran (e.g. state rendered without A5); [] = ran, no issues
        "narrative_warnings": report.get("narrative_warnings"),
        "data_warnings": data_warnings(s),
        "claim_groups": group_claims(s.get("claims") or []),
        "actions_sorted": actions_sorted,
        "p1_actions": [a for a in actions_sorted if a.get("priority") == "P1" and a.get("status") != "dropped"],
        "actions_by_id": {a["action_id"]: a for a in s.get("actions") or []},
        "sources_by_id": sources_by_id,
        "known_ids": known_ids(s),
        "domains": DOMAINS,
        "changes": current_changelog(s),
        "open_questions": [q for q in s.get("open_questions") or [] if q.get("closed_in_version") is None],
        "cited_sources": [sources_by_id[i] for i in cited if i in sources_by_id],
        "cited_missing": [i for i in cited if i not in sources_by_id],
        "unresolved_qa": [i for i in ((s.get("qa") or {}).get("issues") or []) if not i.get("resolved")],
        "is_closed": s.get("status") == "closed",
        "disclaimer": DISCLAIMER,
    }


@pass_context
def _linkify_filter(ctx, text):
    return linkify(text, ctx.get("known_ids") or set())


def _env() -> Environment:
    env = Environment(
        loader=FileSystemLoader(REPORT_DIR),
        autoescape=True,
        undefined=ChainableUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.filters["linkify"] = _linkify_filter
    env.globals.update(
        change_label=claim_change_label,
        risk_css=risk_css,
        status_label=lambda st: STATUS_LABELS.get(st, st or "None reported"),
        priority_label=lambda p: PRIORITY_LABELS.get(p, p or "None reported"),
        category_label=lambda c: CATEGORY_LABELS.get(c, c or "None reported"),
        basis_label=lambda b: BASIS_LABELS.get(b, b or "None reported"),
        timeframe_label=lambda t: TIMEFRAME_LABELS.get(t, t or "None reported"),
    )
    return env


def render_html(state: Any) -> str:
    ctx = build_context(state)
    ctx["css"] = (REPORT_DIR / "style.css").read_text(encoding="utf-8")
    return _env().get_template("template.html").render(**ctx)


def pdf_path_for(state: Any, cases_dir: str | Path = "cases") -> Path:
    s = _to_dict(state)
    return Path(cases_dir) / s["case_id"] / f"report_v{s['version']}.pdf"


def render_pdf(state: Any, cases_dir: str | Path = "cases") -> Path:
    """Write cases/<case_id>/report_v<N>.pdf. Never overwrites an existing version."""
    from playwright.sync_api import sync_playwright  # imported here so HTML-only use needs no browser

    s = _to_dict(state)
    out = pdf_path_for(s, cases_dir)
    if out.exists():
        raise FileExistsError(f"{out} already exists; report versions are never overwritten")
    out.parent.mkdir(parents=True, exist_ok=True)

    html = render_html(s)
    footer = (
        '<div style="font-size:7px;color:#555;width:100%;padding:0 12mm;'
        'display:flex;justify-content:space-between;font-family:Helvetica,Arial,sans-serif;">'
        f'<span>{DISCLAIMER}</span>'
        f'<span>{s["case_id"]} · v{s["version"]} · page <span class="pageNumber"></span>/'
        '<span class="totalPages"></span></span></div>'
    )
    with sync_playwright() as p:
        browser = p.chromium.launch()
        try:
            page = browser.new_page()
            page.set_content(html, wait_until="load")
            page.pdf(
                path=str(out),
                format="A4",
                print_background=True,
                display_header_footer=True,
                header_template="<span></span>",
                footer_template=footer,
                margin={"top": "14mm", "bottom": "18mm", "left": "12mm", "right": "12mm"},
            )
        finally:
            browser.close()
    return out


if __name__ == "__main__":
    # Manual check: python src/report/render.py [state.json] [cases_dir]
    import json
    import sys

    src = Path(sys.argv[1]) if len(sys.argv) > 1 else REPORT_DIR / "sample_state_v1_TEMPORARY.json"
    cases = sys.argv[2] if len(sys.argv) > 2 else "cases"
    print(render_pdf(json.loads(src.read_text(encoding="utf-8")), cases))
